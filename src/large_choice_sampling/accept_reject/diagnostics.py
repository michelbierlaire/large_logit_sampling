"""Diagnostics utilities for accept-reject sampling.

This module provides lightweight containers used to record summary statistics
about the behavior of the accept-reject sampler, in particular the number of
attempted proposals, the number of accepted proposals, and the resulting
acceptance rate.

Michel Bierlaire
Wed Mar 25 2026, 17:13:11
"""

from __future__ import annotations

from dataclasses import dataclass


@dataclass
class AcceptanceStats:
    """Store summary statistics for an accept-reject sampler.

    :param attempts: Total number of proposal draws generated by the sampler.
    :param accepts: Total number of accepted proposals.
    """

    attempts: int = 0
    accepts: int = 0

    @property
    def acceptance_rate(self) -> float:
        """Return the empirical acceptance rate.

        The acceptance rate is defined as the ratio between the number of
        accepted proposals and the total number of proposal attempts. If no
        attempt has been made yet, the value ``0.0`` is returned.

        :return: Empirical acceptance rate.
        """
        if self.attempts == 0:
            return 0.0
        return self.accepts / self.attempts
