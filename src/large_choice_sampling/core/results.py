"""Result containers for large choice-set sampling.

This module defines lightweight data structures used to return results from
key stages of the methodology described in the documentation:

- ``GoodSetResult`` corresponds to the output of the construction phase,
  where a finite elite set ``G`` is built and the remainder ``R`` is
  represented implicitly by frontier states (tail regions).
- ``AcceptRejectResult`` corresponds to the output of a single accept-reject
  draw, including diagnostics about the proposal and acceptance probability.

These containers are intentionally simple and immutable (where appropriate)
to facilitate logging, analysis, and reproducibility.

Michel Bierlaire
Wed Mar 25 2026, 17:18:33
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Generic, TypeVar

from .alternatives import Alternative
from .states import TailRegion

AlternativeT = TypeVar("AlternativeT", bound=Alternative)


@dataclass
class GoodSetResult(Generic[AlternativeT]):
    """Container for the result of the good-set (elite set) generation phase.

    This object summarizes both the explicitly enumerated alternatives (the
    elite set ``G``) and the implicit representation of the remainder ``R``
    through frontier regions, together with diagnostic information about the
    search process.

    :param good_set: List of alternatives explicitly generated by the search
        procedure (the elite set ``G``).
    :param utilities: Mapping from each alternative in ``good_set`` to its
        utility value.
    :param frontier_regions: List of tail regions representing the unexplored
        part of the choice set. Each region corresponds to a state ``s`` and
        defines a subset ``C(s)`` of alternatives.
    :param best_unseen_upper_bound: Upper bound on the utility of the best
        alternative not yet discovered (derived from the frontier states).
    :param states_expanded: Number of states expanded during the search.
    :param leaves_found: Number of complete alternatives discovered.
    :param diagnostics: Additional diagnostic metrics (e.g., frontier size),
        stored as a dictionary of floats.
    :return: An instance of ``GoodSetResult``.
    """
    good_set: list[AlternativeT]
    utilities: dict[AlternativeT, float]
    frontier_regions: list[TailRegion]
    best_unseen_upper_bound: float
    states_expanded: int
    leaves_found: int
    diagnostics: dict[str, float] = field(default_factory=dict)


@dataclass(frozen=True)
class AcceptRejectResult:
    """Container for the result of a single accept-reject sampling step.

    This object records the accepted alternative together with detailed
    information about the proposal draw and acceptance probability, which can
    be used for diagnostics or adaptive refinement strategies.

    :param alternative: The accepted alternative.
    :param proposal_draws: Number of proposal draws required before
        acceptance.
    :param accepted_probability: Acceptance probability used for the
        accepted draw, i.e., ``g(i) / (c_u q(i))``.
    :param proposal_probability: Probability assigned by the proposal
        distribution to the accepted alternative.
    :param component: Identifier of the proposal component that generated
        the accepted alternative (e.g., "elite" or "tail").
    :return: An instance of ``AcceptRejectResult``.
    """
    alternative: Alternative
    proposal_draws: int
    accepted_probability: float
    proposal_probability: float
    component: str
